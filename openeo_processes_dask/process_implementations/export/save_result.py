from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any, Optional

import xarray as xr

from openeo_processes_dask.process_implementations.data_model import RasterCube

logger = logging.getLogger(__name__)

__all__ = ["save_result"]


def _clean_unused_coordinates(ds: xr.Dataset) -> xr.Dataset:
    """
    Remove coordinates that are not referenced by any data variable dimension.
    """
    used_dims = set()

    for var_name in ds.data_vars:
        used_dims.update(ds[var_name].dims)

    for coord_name in list(ds.coords):
        if coord_name not in used_dims and coord_name not in ds.dims:
            ds = ds.drop_vars(coord_name)

    return ds


def _rastercube_to_dataset(data: RasterCube) -> xr.Dataset:
    """
    Convert a RasterCube (xr.DataArray) into an xr.Dataset suitable for export.
    """
    band_dim = data.openeo.band_dims[0] if data.openeo.band_dims else None

    ds = data.to_dataset(
        dim=band_dim,
        name="data" if band_dim is None else None,
        promote_attrs=True,
    )

    ds = _clean_unused_coordinates(ds)

    # Preserve openEO-related dimension hints so downstream tooling can use them.
    ds.attrs["openeo_band_dims"] = list(data.openeo.band_dims or [])
    ds.attrs["openeo_temporal_dims"] = list(data.openeo.temporal_dims or [])
    ds.attrs["openeo_x_dim"] = data.openeo.x_dim
    ds.attrs["openeo_y_dim"] = data.openeo.y_dim
    ds.attrs["openeo_other_dims"] = list(data.openeo.other_dims or [])

    # Preserve CRS when available.
    try:
        crs = data.rio.crs
        if crs is not None:
            ds = ds.rio.write_crs(crs, inplace=False)
            ds.attrs["crs"] = str(crs)
    except Exception:
        logger.debug("Could not propagate CRS from RasterCube.", exc_info=True)

    return ds


def _require_raster2stac():
    try:
        from raster2stac import Raster2STAC
    except ImportError as exc:
        raise ImportError(
            "save_result requires optional export dependencies. "
            "Install them with: pip install openeo-processes-dask[implementations,export]"
        ) from exc

    return Raster2STAC


def _normalize_format(fmt: str) -> str:
    fmt = (fmt or "").strip().lower()
    aliases = {
        "nc": "netcdf",
        "netcdf": "netcdf",
        "zarr": "zarr",
    }
    return aliases.get(fmt, fmt)


def _build_raster2stac(
    ds: xr.Dataset,
    output_folder: Path,
    options: dict[str, Any],
):
    Raster2STAC = _require_raster2stac()

    collection_id = options.get("collection_id")
    if not collection_id:
        collection_id = output_folder.stem.replace(".zarr", "")

    collection_url = options.get("collection_url")
    if not collection_url:
        raise ValueError(
            "save_result requires options['collection_url'] so raster2stac can "
            "generate valid STAC links."
        )

    return Raster2STAC(
        data=ds,
        collection_id=collection_id,
        collection_url=collection_url,
        output_folder=str(output_folder),
        item_prefix=options.get("item_prefix", ""),
        description=options.get("description", "Result generated by save_result."),
        title=options.get("title", collection_id),
        keywords=options.get("keywords"),
        providers=options.get("providers"),
        links=options.get("links"),
        stac_version=options.get("stac_version", "1.0.0"),
        s3_upload=options.get("s3_upload", False),
        bucket_name=options.get("bucket_name"),
        bucket_file_prefix=options.get("bucket_file_prefix"),
        aws_region=options.get("aws_region"),
        aws_access_key=options.get("aws_access_key"),
        aws_secret_key=options.get("aws_secret_key"),
        version=options.get("version"),
        license=options.get("license"),
        sci_doi=options.get("sci_doi"),
        sci_citation=options.get("sci_citation"),
        write_collection_assets=options.get("write_collection_assets", False),
        s3_endpoint_url=options.get("s3_endpoint_url"),
    )


def _read_generated_collection(
    output_folder: Path, collection_id: str
) -> dict[str, Any]:
    """
    raster2stac writes the collection metadata to metadata.json in output_folder.
    If that is unavailable, try a collection-id-based fallback.
    """
    metadata_path = output_folder / "metadata.json"
    if metadata_path.exists():
        with open(metadata_path) as f:
            return json.load(f)

    fallback = output_folder / f"{collection_id}.json"
    if fallback.exists():
        with open(fallback) as f:
            return json.load(f)

    return {
        "stac_version": "1.0.0",
        "type": "Collection",
        "id": collection_id,
        "description": "Result generated by save_result.",
        "href": str(metadata_path),
    }


def _export_netcdf_with_stac(
    ds: xr.Dataset,
    output_folder: Path,
    options: dict[str, Any],
) -> dict[str, Any]:
    """
    Export dataset in NetCDF format and generate STAC metadata through raster2stac.
    """
    output_folder.mkdir(parents=True, exist_ok=True)

    rs2stac = _build_raster2stac(ds=ds, output_folder=output_folder, options=options)
    item_id = options.get("item_id")
    rs2stac.generate_netcdf_stac()

    collection_id = options.get("collection_id", output_folder.name)
    return _read_generated_collection(
        output_folder=output_folder, collection_id=collection_id
    )


def _export_zarr_with_stac(
    ds: xr.Dataset,
    output_folder: Path,
    options: dict[str, Any],
) -> dict[str, Any]:
    """
    Export dataset in Zarr format and generate STAC metadata through raster2stac.
    """
    output_folder.mkdir(parents=True, exist_ok=True)

    rs2stac = _build_raster2stac(ds=ds, output_folder=output_folder, options=options)
    collection_id = options.get(
        "collection_id", output_folder.stem.replace(".zarr", "")
    )
    item_id = options.get("item_id", collection_id)

    rs2stac.generate_zarr_stac(item_id=item_id)

    return _read_generated_collection(
        output_folder=output_folder, collection_id=collection_id
    )


def save_result(
    data: RasterCube,
    format: str = "netcdf",
    options: Optional[dict[str, Any]] = None,
):
    """
    Save processed data and return the generated STAC resource.

    Current prototype conventions:
    - options["path"] is required
    - options["collection_url"] is required for raster2stac
    - supported formats: netcdf, nc, zarr
    """
    options = options or {}
    fmt = _normalize_format(format)

    output_path = options.get("path")
    if not output_path:
        raise ValueError(
            "save_result requires options['path'] to specify where the result is written."
        )

    ds = _rastercube_to_dataset(data)

    logger.info("save_result called with format=%s path=%s", fmt, output_path)

    if fmt == "netcdf":
        # Use a folder because raster2stac writes STAC metadata plus exported data.
        output_folder = Path(output_path).resolve()
        if output_folder.suffix == ".nc":
            output_folder = output_folder.with_suffix("")
        return _export_netcdf_with_stac(
            ds=ds, output_folder=output_folder, options=options
        )

    if fmt == "zarr":
        output_folder = Path(output_path).resolve()
        if output_folder.suffix != ".zarr":
            output_folder = Path(f"{output_folder}.zarr")
        return _export_zarr_with_stac(
            ds=ds, output_folder=output_folder, options=options
        )

    raise ValueError(f"Unsupported format for save_result: {format}")
